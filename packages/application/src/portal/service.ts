import {
  AppError,
  DOMAIN_EVENTS,
  type PortalChangeRequestInput,
  type PortalChangeRequestResultDto,
  type PortalDownloadDto,
  type PortalViewDto,
  type WorkCategory,
} from '@extrawork/contracts';
import {
  hashOpaqueToken,
  setScope,
  tenantScope,
  type PortalLinkRow,
  type TransactionContext,
} from '@extrawork/db';
import { addDays, authorize, systemTenantContext, type TenantContext } from '@extrawork/domain';
import type { AppContext, PublicRequestContext, RequestContext } from '../context.js';
import type { ChangeOrderService } from '../change-orders/service.js';
import { channelRequestContext } from '../intake/system-context.js';
import { buildContractHistory } from '../projects/service.js';

/**
 * The homeowner portal — spec 2026-10-12, D5.
 *
 * A private link, no account, one project, one contact of that project's
 * customer. It shows what the homeowner has been asked to decide and what the
 * designer chose to share with them, and lets them ask for a change, which
 * becomes a proposal on the designer's desk — never something sent to anyone.
 *
 * What it must never show is decided in the repository's SQL, not here: no
 * DRAFT version (so no proposal still with the designer, and no revision being
 * prepared), no document outside a CLIENT folder, nothing from another
 * project. This service only assembles what those queries return.
 *
 * The token is the whole credential, so it is treated like an approval
 * token: generated by the shared opaque-token helper, stored as SHA-256 only,
 * looked up in system scope (it is what names the tenant), and the rest of the
 * request is then narrowed to that tenant so row-level security applies.
 */

/** The format every minted token has: 32 random bytes, base64url. */
const TOKEN_PATTERN = /^[A-Za-z0-9_-]{43}$/;
const DEFAULT_VALID_DAYS = 90;

export interface CreatedPortalLink {
  link: PortalLinkRow;
  portalUrl: string;
  whatsappShareUrl: string | null;
  messageText: string;
}

interface ResolvedPortal {
  linkId: string;
  tenant: TenantContext;
  projectId: string;
  contactId: string;
  expiresAt: Date;
}

export class PortalService {
  constructor(
    readonly app: AppContext,
    private readonly changeOrders: ChangeOrderService,
  ) {}

  // --- Designer side -----------------------------------------------------------

  async createLink(
    ctx: RequestContext,
    projectId: string,
    input: { contactId?: string | undefined; validDays?: number | undefined },
  ): Promise<CreatedPortalLink> {
    authorize(ctx.actor, 'portal:share', {
      organizationId: ctx.tenant.organizationId,
      projectId,
    });
    const project = await this.app.repos.projects.requireById(ctx.tenant, projectId);
    const contactId = input.contactId ?? project.defaultApproverContactId;
    if (!contactId) {
      throw new AppError('VALIDATION_FAILED', {
        message: 'This project has no homeowner contact yet. Add one to the customer first.',
        details: { field: 'contactId' },
      });
    }
    return this.app.uow.transaction((tx) =>
      this.mint(tx, ctx.tenant, {
        projectId,
        contactId,
        createdVia: 'WEB',
        createdByUserId: ctx.actor.userId,
        validDays: input.validDays ?? DEFAULT_VALID_DAYS,
      }),
    );
  }

  /**
   * A fresh link minted because the homeowner texted "contracts" (spec D5:
   * the portal is the answer to that message). Runs in the intake's
   * transaction under its system tenant; the contact was resolved from the
   * sender's own phone number, which is the only credential WhatsApp offers.
   */
  async mintForWhatsApp(
    tx: TransactionContext,
    tenant: TenantContext,
    projectId: string,
    contactId: string,
  ): Promise<CreatedPortalLink> {
    return this.mint(tx, tenant, {
      projectId,
      contactId,
      createdVia: 'WHATSAPP',
      createdByUserId: null,
      validDays: DEFAULT_VALID_DAYS,
    });
  }

  async listLinks(ctx: RequestContext, projectId: string): Promise<PortalLinkRow[]> {
    authorize(ctx.actor, 'portal:share', {
      organizationId: ctx.tenant.organizationId,
      projectId,
    });
    await this.app.repos.projects.requireById(ctx.tenant, projectId);
    return this.app.repos.portal.listForProject(ctx.tenant, projectId);
  }

  async revokeLink(ctx: RequestContext, linkId: string): Promise<void> {
    const link = await this.app.repos.portal.findById(this.app.uow.db, ctx.tenant, linkId);
    if (!link) throw new AppError('NOT_FOUND');
    authorize(ctx.actor, 'portal:share', {
      organizationId: link.organizationId,
      projectId: link.projectId,
    });
    await this.app.uow.transaction(async (tx) => {
      const revoked = await this.app.repos.portal.revoke(tx, ctx.tenant, link.id);
      // Revoking twice is a no-op, not a second audit entry.
      if (!revoked) return;
      await this.app.repos.audit.append(tx, ctx.tenant, [
        {
          aggregateType: 'project',
          aggregateId: link.projectId,
          projectId: link.projectId,
          eventType: DOMAIN_EVENTS.PORTAL_LINK_REVOKED,
          actorType: ctx.actor.userId ? 'USER' : 'SYSTEM',
          actorId: ctx.actor.userId,
          occurredAt: this.app.clock.now(),
          payload: { linkId: link.id, contactId: link.contactId },
        },
      ]);
    });
  }

  private async mint(
    tx: TransactionContext,
    tenant: TenantContext,
    input: {
      projectId: string;
      contactId: string;
      createdVia: 'WEB' | 'WHATSAPP';
      createdByUserId: string | null;
      validDays: number;
    },
  ): Promise<CreatedPortalLink> {
    const project = await this.app.repos.projects.requireById(tenant, input.projectId);
    const contact = await this.app.repos.customers.findContact(tenant, input.contactId);
    // Only a contact of this project's own customer: the portal shows the
    // contract value and every request, which is that household's business.
    if (!contact || contact.customerId !== project.customerId) {
      throw new AppError('VALIDATION_FAILED', {
        message: 'Choose a contact of this project’s customer.',
        details: { field: 'contactId' },
      });
    }
    if (!contact.phoneE164 && !contact.emailNormalized) {
      // An erased contact keeps no details; issuing them a link would recreate
      // a relationship the erasure ended.
      throw new AppError('CONTACT_NOT_FOUND');
    }

    const now = this.app.clock.now();
    const expiresAt = new Date(now.getTime() + input.validDays * 86_400_000);
    const { link, token } = await this.app.repos.portal.create(tx, tenant, {
      projectId: project.id,
      contactId: contact.id,
      createdVia: input.createdVia,
      createdByUserId: input.createdByUserId,
      expiresAt,
    });
    await this.app.repos.audit.append(tx, tenant, [
      {
        aggregateType: 'project',
        aggregateId: project.id,
        projectId: project.id,
        eventType: DOMAIN_EVENTS.PORTAL_LINK_CREATED,
        actorType: input.createdByUserId ? 'USER' : 'SYSTEM',
        actorId: input.createdByUserId,
        occurredAt: now,
        // Never the token, never its hash: the audit chain is read by support.
        payload: {
          linkId: link.id,
          contactId: contact.id,
          createdVia: input.createdVia,
          expiresAt: expiresAt.toISOString(),
        },
      },
    ]);

    const organization = await this.app.repos.organizations.findById(tenant);
    const base = this.app.env.WEB_PUBLIC_URL.replace(/\/+$/, '');
    const portalUrl = `${base}/p/${token}`;
    const messageText = portalMessage({
      contactName: contact.name,
      projectTitle: project.title,
      organizationName: organization?.displayName ?? 'your designer',
      portalUrl,
      expiresAt,
    });
    const digits = contact.phoneE164?.replace(/\D/g, '') ?? null;
    return {
      link,
      portalUrl,
      whatsappShareUrl: digits
        ? `https://wa.me/${digits}?text=${encodeURIComponent(messageText)}`
        : null,
      messageText,
    };
  }

  // --- Homeowner side (public) -----------------------------------------------

  async view(plainToken: string, ctx: PublicRequestContext): Promise<PortalViewDto> {
    const portal = await this.resolve(plainToken, ctx);
    const { tenant, projectId } = portal;

    const [organization, project, contact, sources, pending, requests, documents, milestones] =
      await Promise.all([
        this.app.repos.organizations.findById(tenant),
        this.app.repos.projects.requireById(tenant, projectId),
        this.app.repos.customers.requireContact(tenant, portal.contactId),
        this.app.repos.projects.contractHistorySources(tenant, projectId),
        this.app.repos.projects.pendingTotals(tenant, projectId),
        this.app.repos.portal.listSentRequests(tenant, projectId),
        this.app.repos.portal.listClientDocuments(tenant, projectId),
        this.app.repos.milestones.listForProject(this.app.uow.db, tenant, projectId),
      ]);
    if (!organization) throw new AppError('PORTAL_LINK_INVALID');

    await this.app.repos.portal.recordView(tenant, portal.linkId);

    const now = this.app.clock.now();
    const history = buildContractHistory(project, sources);
    return {
      organizationName: organization.displayName,
      contactName: contact.name,
      project: {
        number: project.projectNumber,
        title: project.title,
        description: project.description,
        city: cityOf(project.siteAddressJson),
        status: project.status,
        startDate: project.startDate,
        expectedCompletionDate: project.expectedCompletionDate,
        revisedCompletionDate:
          project.expectedCompletionDate && project.approvedScheduleDeltaDays !== 0
            ? addDays(project.expectedCompletionDate, project.approvedScheduleDeltaDays)
            : null,
      },
      contract: {
        currency: project.currency,
        originalTotalMinor: Number(project.baselineTotalMinor),
        approvedDeltaMinor: Number(project.approvedDeltaMinor),
        currentTotalMinor: Number(project.revisedTotalMinor),
        pendingDeltaMinor: Number(pending.pendingDeltaMinor),
        history: history.entries,
      },
      requests: requests.map((request) => ({
        id: request.changeOrderId,
        number: request.number,
        versionNumber: request.versionNumber,
        title: request.title,
        scope: request.scope,
        room: request.room,
        workCategory: request.workCategory as WorkCategory | null,
        status: request.status as PortalViewDto['requests'][number]['status'],
        totalDeltaMinor: Number(request.totalDeltaMinor),
        scheduleDeltaDays: request.scheduleDeltaDays,
        sentAt: request.sentAt?.toISOString() ?? null,
        decidedAt: request.decidedAt?.toISOString() ?? null,
        actionable:
          (request.status === 'SENT' || request.status === 'VIEWED') &&
          (!request.expiresAt || request.expiresAt.getTime() > now.getTime()),
        evidenceReady: request.evidenceDocumentId !== null,
        evidenceDocumentId: request.evidenceDocumentId,
      })),
      // A file is listed once it is safe to hand out; one still being scanned
      // (or refused by the scan) would only produce a failed download.
      documents: documents
        .filter((d) => d.kind !== 'FILE' || d.scanStatus === 'CLEAN')
        .map((d) => ({
          id: d.id,
          folderName: d.folderName,
          folderVisibility: d.folderVisibility,
          kind: d.kind,
          title: d.title,
          url: d.url,
          body: d.body,
          mimeType: d.mimeType,
          byteSize: d.byteSize === null ? null : Number(d.byteSize),
          createdAt: d.createdAt.toISOString(),
        })),
      milestones: milestones
        .filter((m) => m.clientVisible)
        .map((m) => ({
          id: m.id,
          title: m.title,
          kind: m.kind,
          dueDate: m.dueDate,
          completedAt: m.completedAt?.toISOString() ?? null,
        })),
      expiresAt: portal.expiresAt.toISOString(),
      canAskForChange: project.status === 'ACTIVE',
    };
  }

  /**
   * A short-lived signed URL for a client-visible file or a ready evidence
   * pack of one of this project's sent requests, always as an attachment
   * (D10: nothing a homeowner downloads is rendered by the browser).
   */
  async download(
    plainToken: string,
    documentId: string,
    ctx: PublicRequestContext,
  ): Promise<PortalDownloadDto> {
    const { tenant, projectId } = await this.resolve(plainToken, ctx);
    const ttl = this.app.env.SIGNED_URL_TTL_SECONDS;

    const document = await this.app.repos.portal.findClientDocument(tenant, projectId, documentId);
    if (document) {
      if (document.kind !== 'FILE' || !document.fileObjectId) {
        throw new AppError('DOCUMENT_NOT_FOUND');
      }
      const file = await this.app.repos.files.requireById(tenant, document.fileObjectId);
      this.app.repos.files.assertViewable(file);
      return {
        downloadUrl: await this.app.objectStore.createDownload(
          file.promotedStorageKey ?? file.storageKey,
          ttl,
          file.originalFilename,
          { forceDownload: true },
        ),
        filename: file.originalFilename,
      };
    }

    const evidence = await this.app.repos.portal.findReadyEvidence(tenant, projectId, documentId);
    if (!evidence) throw new AppError('DOCUMENT_NOT_FOUND');
    const filename = `${evidence.changeOrderNumber}-evidence.pdf`;
    return {
      downloadUrl: await this.app.objectStore.createDownload(evidence.storageKey, ttl, filename, {
        forceDownload: true,
      }),
      filename,
    };
  }

  /**
   * The homeowner asks for a change. It becomes a proposal for the designer
   * (slice B's `createProposal`, origin PORTAL, attributed to the link's
   * contact) — the same path a site-team message takes, so the designer
   * reviews, prices and sends it like any other.
   */
  async requestChange(
    plainToken: string,
    input: PortalChangeRequestInput,
    ctx: PublicRequestContext,
  ): Promise<PortalChangeRequestResultDto> {
    const portal = await this.resolve(plainToken, ctx);
    const project = await this.app.repos.projects.requireById(portal.tenant, portal.projectId);
    if (project.status !== 'ACTIVE') {
      throw new AppError('PROJECT_CLOSED', {
        message: 'This project is closed. Contact your designer directly about new work.',
      });
    }

    const created = await this.changeOrders.createProposal(
      channelRequestContext(portal.tenant, portal.projectId, 'extrawork-homeowner-portal'),
      portal.projectId,
      {
        description: input.description,
        ...(input.room ? { room: input.room } : {}),
        ...(input.workCategory ? { workCategory: input.workCategory } : {}),
        ...(input.reason ? { reason: input.reason } : {}),
        attachmentIds: [],
      },
      { origin: 'PORTAL', submittedByContactId: portal.contactId },
    );

    const organization = await this.app.repos.organizations.findById(portal.tenant);
    return {
      number: created.number,
      message:
        `Sent to ${organization?.displayName ?? 'your designer'} as ${created.number}. ` +
        'They will review it and send you the price and timing to approve. Nothing changes ' +
        'until you approve it.',
    };
  }

  /**
   * Resolves the token and narrows the rest of the request to its tenant.
   * A malformed, unknown, revoked or expired token is the same 404 with a
   * reason the page can explain; the reason never confirms anything to
   * someone who does not already hold a real link.
   */
  private async resolve(plainToken: string, ctx: PublicRequestContext): Promise<ResolvedPortal> {
    if (!TOKEN_PATTERN.test(plainToken)) {
      throw new AppError('PORTAL_LINK_INVALID', { details: { reason: 'INVALID' } });
    }
    const hash = hashOpaqueToken(plainToken);
    const lookup = await this.app.repos.portal.findByTokenHash(hash);
    if (!lookup) {
      const dead = await this.app.repos.portal.describeDeadToken(hash);
      throw new AppError('PORTAL_LINK_INVALID', { details: { reason: dead ?? 'INVALID' } });
    }

    // The token named the tenant; from here the request runs under the same
    // row-level security as a signed-in one (as `PublicApprovalService` does).
    setScope(tenantScope(lookup.organizationId));
    return {
      linkId: lookup.linkId,
      tenant: systemTenantContext(lookup.organizationId, ctx.requestId),
      projectId: lookup.projectId,
      contactId: lookup.contactId,
      expiresAt: lookup.expiresAt,
    };
  }
}

function portalMessage(input: {
  contactName: string;
  projectTitle: string;
  organizationName: string;
  portalUrl: string;
  expiresAt: Date;
}): string {
  const first = input.contactName.trim().split(/\s+/)[0] ?? input.contactName;
  const until = input.expiresAt.toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'Asia/Kolkata',
  });
  return [
    `Hi ${first}, here is the record for ${input.projectTitle} from ${input.organizationName}:`,
    'every change request and its status, the contract value, and the files shared with you.',
    '',
    input.portalUrl,
    '',
    `This link is private to you and works until ${until}. You can also ask for a change from it.`,
  ].join('\n');
}

function cityOf(address: Record<string, unknown> | null): string | null {
  const city = address?.city;
  return typeof city === 'string' && city.trim() ? city.trim() : null;
}
