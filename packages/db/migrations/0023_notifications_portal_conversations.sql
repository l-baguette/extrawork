-- Three-party workspace, part 4: notifications, the homeowner portal, the
-- private calendar feed, and WhatsApp conversation state.
-- Spec decisions D5, D6, D14.

-- ---------------------------------------------------------------------------
-- Notifications: one row per recipient.
-- ---------------------------------------------------------------------------
--
-- Fan-out at write time rather than a shared feed with per-user read marks:
-- the audience of an event depends on project grants at that moment, and a
-- collaborator removed tomorrow must not gain or lose history retroactively.

CREATE TABLE notifications (
  id              uuid PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  user_id         uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  project_id      uuid,
  kind            text NOT NULL CHECK (kind ~ '^[A-Z][A-Z_]{2,40}$'),
  title           text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  body            text CHECK (body IS NULL OR length(body) <= 1000),
  -- A path inside the web app, never an absolute URL: a notification must not
  -- be able to send someone off-site.
  link_path       text CHECK (link_path IS NULL OR (link_path ~ '^/[^/]' AND length(link_path) <= 500)),
  actor_label     text CHECK (actor_label IS NULL OR length(actor_label) <= 200),
  -- Reminders are generated by a daily sweep; the key makes the sweep idempotent.
  dedupe_key      text CHECK (dedupe_key IS NULL OR length(dedupe_key) <= 200),
  created_at      timestamptz NOT NULL DEFAULT now(),
  read_at         timestamptz,
  CONSTRAINT notifications_project_tenant_fk
    FOREIGN KEY (organization_id, project_id)
    REFERENCES projects (organization_id, id) ON DELETE CASCADE
);

CREATE INDEX notifications_user_idx
  ON notifications (user_id, organization_id, created_at DESC);
CREATE INDEX notifications_unread_idx
  ON notifications (user_id, organization_id) WHERE read_at IS NULL;
CREATE UNIQUE INDEX notifications_dedupe_uidx
  ON notifications (organization_id, user_id, dedupe_key) WHERE dedupe_key IS NOT NULL;

CREATE TABLE notification_preferences (
  organization_id      uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  user_id              uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  email_enabled        boolean NOT NULL DEFAULT true,
  completion_reminders boolean NOT NULL DEFAULT true,
  reminder_lead_days   integer NOT NULL DEFAULT 3 CHECK (reminder_lead_days BETWEEN 0 AND 30),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (organization_id, user_id)
);

-- ---------------------------------------------------------------------------
-- Homeowner portal links (D5).
-- ---------------------------------------------------------------------------
--
-- A read-only window onto one project for one customer contact, without an
-- account. Same token discipline as approval links: 32 random bytes, only the
-- SHA-256 stored, revocable, expiring.

CREATE TABLE project_portal_links (
  id                 uuid PRIMARY KEY,
  organization_id    uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  project_id         uuid NOT NULL,
  contact_id         uuid NOT NULL,
  token_sha256       bytea NOT NULL UNIQUE,
  created_via        text NOT NULL DEFAULT 'WEB' CHECK (created_via IN ('WEB','WHATSAPP')),
  created_by_user_id uuid REFERENCES users(id),
  expires_at         timestamptz NOT NULL,
  revoked_at         timestamptz,
  last_viewed_at     timestamptz,
  view_count         integer NOT NULL DEFAULT 0 CHECK (view_count >= 0),
  created_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_portal_links_project_tenant_fk
    FOREIGN KEY (organization_id, project_id)
    REFERENCES projects (organization_id, id) ON DELETE CASCADE,
  CONSTRAINT project_portal_links_contact_tenant_fk
    FOREIGN KEY (organization_id, contact_id)
    REFERENCES contacts (organization_id, id) ON DELETE CASCADE
);

CREATE INDEX project_portal_links_project_idx
  ON project_portal_links (organization_id, project_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Private calendar feed (D14).
-- ---------------------------------------------------------------------------

CREATE TABLE calendar_feed_tokens (
  id              uuid PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  user_id         uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_sha256    bytea NOT NULL UNIQUE,
  created_at      timestamptz NOT NULL DEFAULT now(),
  revoked_at      timestamptz,
  last_fetched_at timestamptz
);

CREATE UNIQUE INDEX calendar_feed_tokens_active_uidx
  ON calendar_feed_tokens (organization_id, user_id) WHERE revoked_at IS NULL;

-- ---------------------------------------------------------------------------
-- WhatsApp conversation state (D6).
-- ---------------------------------------------------------------------------
--
-- Keyed by phone number, because a sender is not tied to one workspace: the
-- same foreman may text about two design firms' projects. That makes the row
-- cross-tenant routing state, so it carries no organization_id at all and is
-- readable only under the system scope the intake runs in.
--
--   pending    a message held until the sender says which project it is for
--   sticky_*   the project the sender last used, so follow-ups need no code
--   last_item  what the last message became, for the REQUEST / FILE corrections

CREATE TABLE whatsapp_conversations (
  id                     uuid PRIMARY KEY,
  phone_e164             text NOT NULL UNIQUE CHECK (phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  pending                jsonb,
  pending_expires_at     timestamptz,
  sticky_organization_id uuid REFERENCES organizations(id) ON DELETE SET NULL,
  sticky_project_id      uuid,
  sticky_until           timestamptz,
  last_item              jsonb,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  CHECK ((pending IS NULL) = (pending_expires_at IS NULL))
);

CREATE TRIGGER whatsapp_conversations_touch BEFORE UPDATE ON whatsapp_conversations
  FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

ALTER TABLE whatsapp_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE whatsapp_conversations FORCE ROW LEVEL SECURITY;
CREATE POLICY system_only ON whatsapp_conversations
  USING (current_setting('extrawork.organization_id', true) = '*')
  WITH CHECK (current_setting('extrawork.organization_id', true) = '*');

-- ---------------------------------------------------------------------------
-- Inbound messages: richer outcomes, and media that outlives the webhook.
-- ---------------------------------------------------------------------------
--   SAVED            filed into the project as a document or note
--   AWAITING_CHOICE  held until the sender picks a project
--   ANSWERED         a command (help, projects, contracts) that was answered

ALTER TYPE inbound_status ADD VALUE IF NOT EXISTS 'SAVED';
ALTER TYPE inbound_status ADD VALUE IF NOT EXISTS 'AWAITING_CHOICE';
ALTER TYPE inbound_status ADD VALUE IF NOT EXISTS 'ANSWERED';

ALTER TABLE inbound_messages
  -- The provider's media references, so attachments on a message held for a
  -- project choice can still be fetched once the sender answers.
  ADD COLUMN media_refs jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- Who sent it when the sender is a customer contact rather than site team.
  ADD COLUMN contact_id uuid,
  ADD COLUMN document_id uuid,
  ADD COLUMN resolved_by_inbound_message_id uuid REFERENCES inbound_messages(id),
  ADD CONSTRAINT inbound_messages_contact_tenant_fk
    FOREIGN KEY (organization_id, contact_id) REFERENCES contacts (organization_id, id),
  ADD CONSTRAINT inbound_messages_document_tenant_fk
    FOREIGN KEY (organization_id, document_id) REFERENCES project_documents (organization_id, id);

-- ---------------------------------------------------------------------------
-- Row-level security (mirrors 0019).
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  target text;
BEGIN
  FOREACH target IN ARRAY ARRAY[
    'notifications','notification_preferences','project_portal_links','calendar_feed_tokens'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', target);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', target);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
        USING (
          current_setting('extrawork.organization_id', true) = '*'
          OR organization_id::text = current_setting('extrawork.organization_id', true)
        )
        WITH CHECK (
          current_setting('extrawork.organization_id', true) = '*'
          OR organization_id::text = current_setting('extrawork.organization_id', true)
        )
    $p$, target);
  END LOOP;
END $$;
